import '../fixtures.mjs';
import { TEST_TMP_ROOT } from '../fixtures.mjs';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { randomUUID, createHash } from 'node:crypto';
process.env.CVW_INTERNAL_TOKEN = 'whitebox-fixture-token';
process.env.CVW_GATEWAY_BASE_URL = 'http://127.0.0.1:1';
const { config } = await import('../../apps/worker-bridge/src/config.mjs');
const { prepareWhiteboxSkills, defaultWhiteboxSkills } = await import('../../apps/shared/whitebox.mjs');
const { prepareJobWorkspace, verifyJobIsolation } = await import('../../apps/worker-bridge/src/job-workspace.mjs');
test('only the selected whitebox skill is mounted; host adaptations and successive user edits are recorded', async () => {
  const sid = 'sess_' + randomUUID(); const jid = 'job_' + randomUUID();
  const root = join(config.storage.sessionsRoot, config.storage.sessionsSubdir);
  const options = { raw: config.raw, repoRoot: config.repoRoot };
  const legacy = config.raw.whitebox.skills.find(s => s.version === '0.9.3');
  const original = await readFile(join(config.repoRoot, legacy.archive));
  const first = await prepareWhiteboxSkills(root, sid, { builtin: 'none', text: '', configured: [legacy] }, null, options);
  const ws = await prepareJobWorkspace({ sessionId: sid, jobId: jid, mode: 'blockout_3d', prompt: 'Render a cube.', experimentalSkills: first, agentWsPath: '/workspace' });
  assert.deepEqual(ws.skills, ['blockout-previs']);
  const meta = JSON.parse(await readFile(join(ws.bookDir, '_meta.json')));
  assert.equal(meta.whitebox_compat[0].adapter, 'cvw-blockout-093-host-v1');
  const cli = await readFile(join(ws.ws, '.claude/skills/blockout-previs/scripts/job.py'), 'utf8');
  assert.match(cli, /else None/); assert.match(cli, /--budget',type=int,default=0/); assert.equal(meta.whitebox_compat[0].transport.format, 'lossless-png'); assert.match(cli, /else 180,remaining-5/);
  assert.equal(await readFile(join(ws.bookDir, 'skill-compat/blockout-previs/scripts/job.py'), 'utf8'), cli);
  assert.match(await readFile(ws.promptPath, 'utf8'), /--budget 0/);
  assert.equal(verifyJobIsolation(sid, jid, 'blockout_3d').ok, true);
  assert.equal(createHash('sha256').update(original).digest('hex'), first.configured[0].archive_sha256);
  const native = join(ws.ws, '.home/.claude/projects/-workspace'); await mkdir(native, { recursive: true });
  await writeFile(join(native, sid.slice(5) + '.jsonl'), '{}\n');
  await writeFile(join(ws.ws, 'src/scene.json'), '{"previous":true}');
  const next = await prepareWhiteboxSkills(root, sid, { text: 'Use a different single skill.', configured: [], clear_archive: true }, first, options);
  const edited = await prepareJobWorkspace({ sessionId: sid, jobId: 'job_' + randomUUID(), mode: 'blockout_3d', prompt: 'Change the camera.', experimentalSkills: next });
  assert.equal(edited.isContinuation, true);
  assert.deepEqual(await readdir(join(ws.ws, '.claude/skills')), ['custom-prompt-skill']);
  assert.equal(await readFile(join(ws.ws, 'src/scene.json'), 'utf8'), '{"previous":true}');
  assert.match(await readFile(edited.promptPath, 'utf8'), /Previous or unmounted skills are not applicable/);
  assert.equal(await readFile(join(ws.bookDir, '_meta.json'), 'utf8'), JSON.stringify(meta, null, 2));
  assert.equal(await readFile(join(ws.bookDir, 'skill-compat/blockout-previs/scripts/job.py'), 'utf8'), cli);
});


test('0.11.1 keeps its video-first soft target and scoped edit contract, with archived host-only changes', async () => {
  const sid = 'sess_' + randomUUID(), root = join(config.storage.sessionsRoot, config.storage.sessionsSubdir);
  const spec = await prepareWhiteboxSkills(root, sid, defaultWhiteboxSkills(config.raw), null, { raw: config.raw, repoRoot: config.repoRoot });
  assert.equal(spec.configured[0].version, '0.11.1');
  const ws = await prepareJobWorkspace({ sessionId: sid, jobId: 'job_' + randomUUID(), mode: 'blockout_3d', prompt: 'A complex real story.', modelSelection: {profile_id:'whitebox-deepseek'}, experimentalSkills: spec });
  const meta = JSON.parse(await readFile(join(ws.bookDir, '_meta.json')));
  assert.deepEqual(ws.skills, ['blockout-previs']);
  assert.equal(meta.whitebox_host.context_policy, 'current-phase-v1');
  assert.equal(meta.whitebox_host.version, 'cvw-whitebox-cc-v9');
  assert.equal(meta.whitebox_host.stage_transport, 'chat-json-v1');
  assert.equal(meta.whitebox_host.user_prompt, 'A complex real story.');
  const record = meta.whitebox_compat[0];
  assert.equal(record.adapter, 'cvw-blockout-0111-host-v1');
  assert.equal(record.original_files_sha256['scripts/job.py'], record.adapted_files_sha256['scripts/job.py']);
  assert.equal(record.original_files_sha256['SKILL.md'], record.adapted_files_sha256['SKILL.md']);
  const prompt = await readFile(ws.promptPath, 'utf8');
  assert.match(prompt, /Delivery target: video/); assert.match(prompt, /600 seconds is a soft target/);
  assert.match(prompt, /mcp__whitebox__submit/);
  assert.doesNotMatch(prompt, /Run foreground Bash commands/);
  assert.match(prompt, /render_success separately from quality_pass/);
  assert.doesNotMatch(prompt, /initialize a fresh skill job|invoke scripts\/job.py init with --budget 0/);
  const cli = await readFile(join(ws.bookDir, 'skill-compat/blockout-previs/scripts/job.py'));
  assert.equal(createHash('sha256').update(cli).digest('hex'), record.original_files_sha256['scripts/job.py']);
});
